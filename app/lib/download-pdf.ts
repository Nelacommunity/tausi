export async function downloadPDF({
  title,
  html,
  isFree,
}: {
  title: string;
  html: string;
  isFree: boolean;
}) {
  const origin = window.location.origin;
  const date = new Date().toLocaleDateString("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });

  const watermarkHtml = isFree
    ? `<div style="position:fixed;top:50%;left:50%;transform:translate(-50%,-50%) rotate(-35deg);
         opacity:0.07;text-align:center;pointer-events:none;z-index:0;user-select:none">
         <img src="/favicon.ico" width="130" height="130" style="display:block;margin:0 auto 10px">
         <div style="font-size:26pt;font-weight:bold;font-family:Arial,sans-serif;color:#000;letter-spacing:3px">
           tausi.app
         </div>
       </div>
       <div style="position:fixed;bottom:18px;right:22px;font-size:8pt;color:rgba(0,0,0,0.22);
         font-family:Arial,sans-serif;z-index:0">
         Generated by tausi.app
       </div>`
    : "";

  const doc = `<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8">
  <title>${esc(title)}</title>
  <base href="${origin}">
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.16.21/dist/katex.min.css">
  <style>
    @page { margin: 2.5cm 2.2cm; }
    * { box-sizing: border-box; }
    body {
      font-family: Georgia, 'Times New Roman', serif;
      font-size: 11pt;
      line-height: 1.75;
      color: #111;
      background: #fff;
      margin: 0;
    }
    .doc-header { margin-bottom: 28px; padding-bottom: 12px; border-bottom: 2px solid #222; }
    .doc-title  { font-size: 22pt; font-weight: bold; color: #111; margin: 0 0 4px; }
    .doc-meta   { font-size: 9pt; color: #666; font-family: Arial, sans-serif; }
    h1 { font-size: 17pt; font-weight: bold; color: #111; border-bottom: 1px solid #ccc;
         padding-bottom: 4px; margin: 24px 0 10px; }
    h2 { font-size: 14pt; font-weight: bold; color: #222; margin: 20px 0 8px; }
    h3 { font-size: 12pt; font-weight: bold; color: #333; margin: 16px 0 6px; }
    h4 { font-size: 11pt; font-weight: bold; margin: 12px 0 4px; }
    p  { margin: 0 0 10px; }
    ul { list-style-type: disc;    padding-left: 22px; margin: 0 0 10px; }
    ol { list-style-type: decimal; padding-left: 22px; margin: 0 0 10px; }
    li { margin-bottom: 3px; }
    strong { font-weight: bold; color: #000; }
    em { font-style: italic; }
    u  { text-decoration: underline; }
    s  { text-decoration: line-through; }
    table { border-collapse: collapse; width: 100%; margin: 12px 0; font-size: 10pt; }
    th { background: #f0f0f0; border: 1px solid #bbb; padding: 6px 10px;
         text-align: center; font-weight: bold; }
    td { border: 1px solid #ccc; padding: 6px 10px; text-align: center; }
    code { background: #f5f5f5; border: 1px solid #ddd; border-radius: 2px;
           padding: 1px 4px; font-family: 'Courier New', monospace; font-size: 9pt; color: #333; }
    pre  { background: #f5f5f5; border: 1px solid #ddd; border-radius: 3px;
           padding: 12px; overflow-x: auto; margin: 8px 0; }
    pre code { background: none; border: none; padding: 0; }
    blockquote { border-left: 3px solid #666; padding-left: 14px; color: #555;
                 margin: 10px 0; font-style: italic; }
    hr { border: none; border-top: 1px solid #ccc; margin: 20px 0; }
    /* Override any dark-theme color classes — all text prints dark */
    * { color: #111 !important; background-color: transparent !important; }
    strong { color: #000 !important; }
    th  { background-color: #f0f0f0 !important; }
    pre, code { background-color: #f5f5f5 !important; }
    .doc-meta { color: #666 !important; }
    .watermark-footer { color: rgba(0,0,0,0.22) !important; }
    /* KaTeX */
    .katex-display { text-align: center; margin: 8px 0; }
  </style>
</head>
<body>
  ${watermarkHtml}
  <div class="doc-header">
    <div class="doc-title">${esc(title)}</div>
    <div class="doc-meta">Generated by Tausi · ${date}</div>
  </div>
  <div>${html}</div>
  <script>
    window.addEventListener('load', function() {
      setTimeout(function() { window.print(); }, 700);
    });
  </script>
</body>
</html>`;

  const win = window.open("", "_blank", "width=920,height=700,scrollbars=yes");
  if (win) {
    win.document.write(doc);
    win.document.close();
  }
}

function esc(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
