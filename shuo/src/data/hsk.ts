export interface Word {
  hanzi: string;
  pinyin: string;
  meaning: string;
}

const parse = (src: string): Word[] =>
  src.split('\n').map((l) => {
    const [hanzi, pinyin, meaning] = l.split('|');
    return { hanzi, pinyin, meaning };
  });

export const HSK_DECKS: Record<string, Word[]> = {
  'HSK 1': parse(HSK1),
  'HSK 2': parse(HSK2),
};

const index = new Map<string, Word>();
Object.values(HSK_DECKS).forEach((ws) => ws.forEach((w) => index.set(w.hanzi, w)));
export const lookupBuiltin = (hanzi: string) => index.get(hanzi);
